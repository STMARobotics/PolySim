import * as cdk from 'aws-cdk-lib';
import { BackendStack, CertificateStack, FrontendStack } from '../lib/stacks';
import {production} from '../lib/config';
const app=new cdk.App();
cdk.Tags.of(app).add('AppName','PolySim');
cdk.Tags.of(app).add('Environment','production');
const account=production.account, env={account,region:production.region};
const edge=new CertificateStack(app,production.certificateStackName,{env:{account,region:production.edgeRegion},crossRegionReferences:true});
const backend=new BackendStack(app,production.backendStackName,{env,crossRegionReferences:true});
new FrontendStack(app,production.frontendStackName,{env,crossRegionReferences:true,backend,edge});
app.synth();
